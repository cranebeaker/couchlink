"""Writes the stand-in (proxy) DLL sources for the Couchlink hook, from the real Windows system DLLs.

    python -I hook/tools/gen_proxy_defs.py

For each system DLL a game may load (version, winmm, dinput8, xinput*) and each architecture this makes, in hook/proxy/:
  <name>-<arch>.def  the export list of the real DLL (names and ordinals), so the stand-in answers every call;
  <name>-<arch>.asm  one jump stub per export: it jumps through a table that the stand-in fills with the
                     addresses of the real DLL's functions when it starts (src/proxy_forward.inl);
  <name>-<arch>.cpp  the export names for that table.
The files are checked in; run this again only when a new Windows adds exports to one of these DLLs.
"""
import struct
import sys
from pathlib import Path

NAMES = ["version", "winmm", "dinput8", "xinput1_3", "xinput1_4", "xinput9_1_0"]
DIRS = {"x64": Path(r"C:\Windows\System32"), "x86": Path(r"C:\Windows\SysWOW64")}
OUT = Path(__file__).resolve().parent.parent / "proxy"
SKIP = {"DllMain"}  # exported by some xinput versions; nobody calls it, and it would clash with ours


def exports(path):
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    assert data[pe:pe + 4] == b"PE\0\0"
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    dd = opt + (112 if magic == 0x20B else 96)
    exp_rva, _ = struct.unpack_from("<II", data, dd)
    secs = []
    sec = opt + opt_size
    for i in range(nsec):
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, sec + 8 + i * 40)
        secs.append((va, max(vsize, rsize), raw))

    def off(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return raw + rva - va
        raise ValueError(hex(rva))

    d = off(exp_rva)
    base, nfun, nnames, fun_rva, names_rva, ord_rva = struct.unpack_from("<IIIIII", data, d + 16)
    fun = off(fun_rva)
    named = {}
    for i in range(nnames):
        name_rva = struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0]
        idx = struct.unpack_from("<H", data, off(ord_rva) + 2 * i)[0]
        end = data.index(b"\0", off(name_rva))
        named[idx] = data[off(name_rva):end].decode("ascii")
    out = []
    for i in range(nfun):
        rva = struct.unpack_from("<I", data, fun + 4 * i)[0]
        if rva and named.get(i) not in SKIP:
            out.append((base + i, named.get(i)))
    return out


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*"):
        old.unlink()
    for arch, folder in DIRS.items():
        for name in NAMES:
            dll = folder / f"{name}.dll"
            if not dll.exists():
                print(f"skip {arch}/{name}: {dll} does not exist")
                continue
            items = exports(dll)
            sym = lambda ordinal, export: export or f"ordinal{ordinal}"
            word = "qword" if arch == "x64" else "dword"
            size = 8 if arch == "x64" else 4

            def_lines = [f"; Generated by hook/tools/gen_proxy_defs.py from {name}.dll ({arch}).", "EXPORTS"]
            for ordinal, export in items:
                def_lines.append(f"    {sym(ordinal, export)} @{ordinal}" + ("" if export else " NONAME"))
            (OUT / f"{name}-{arch}.def").write_text("\n".join(def_lines) + "\n", encoding="ascii")

            asm = [f"; Generated by hook/tools/gen_proxy_defs.py from {name}.dll ({arch}). One jump per export, through cl_fwd."]
            if arch == "x86":
                asm += [".386", ".model flat, C"]
            asm += ["OPTION CASEMAP:NONE", "OPTION PROLOGUE:NONE", "OPTION EPILOGUE:NONE", ".code"]
            for i, (ordinal, export) in enumerate(items):
                s = sym(ordinal, export)
                asm += [f"PUBLIC {s}", f"{s} PROC", f"    jmp {word} ptr [cl_fwd + {i * size}]", f"{s} ENDP"]
            asm += [".data", "PUBLIC cl_fwd", f"cl_fwd {word.upper()} {max(len(items), 1)} dup(0)", "END"]
            (OUT / f"{name}-{arch}.asm").write_text("\n".join(asm) + "\n", encoding="ascii")

            cpp = [f"// Generated by hook/tools/gen_proxy_defs.py from {name}.dll ({arch}).",
                   '#include "../src/proxy_forward.h"', f'#define CL_PROXY_NAME L"{name}"', "static const ClFwdExport kExports[] = {"]
            for ordinal, export in items:
                cpp.append(f'    {{"{export}", {ordinal}}},' if export else f"    {{nullptr, {ordinal}}},")
            cpp += ["};", '#include "../src/proxy_forward.inl"']
            (OUT / f"{name}-{arch}.cpp").write_text("\n".join(cpp) + "\n", encoding="ascii")
            print(f"{arch}/{name}: {len(items)} exports")


if __name__ == "__main__":
    sys.exit(main())
